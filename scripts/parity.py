#!/usr/bin/env python3
"""Builds docs/FEATURE_PARITY_MATRIX.md from docs/parity/features.tsv and docs/parity/status.tsv.

features.tsv: id, feature, reference capability, our implementation, priority, dependencies
status.tsv:   id, status, evidence, limitations   (missing id = "Not implemented")

Statuses: Verified | Unverified | Blocked | Excluded | Not implemented | In progress
"""
import collections, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
LABEL = {
    "Verified": "Implemented and verified",
    "Unverified": "Implemented, not fully verified",
    "Blocked": "Blocked by external dependency or credential",
    "Excluded": "Intentionally excluded",
    "Not implemented": "Not implemented",
    "In progress": "In progress",
}

def rows(name, n):
    out = []
    for i, line in enumerate((root / "docs/parity" / name).read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != n:
            sys.exit(f"{name}:{i}: expected {n} tab-separated fields, got {len(parts)}")
        out.append([p.strip() for p in parts])
    return out

features = rows("features.tsv", 6)
status = {r[0]: r[1:] for r in rows("status.tsv", 4)}
ids = [f[0] for f in features]
dupes = [i for i, c in collections.Counter(ids).items() if c > 1]
unknown = [i for i in status if i not in ids]
bad = [i for i, s in status.items() if s[0] not in LABEL]
if dupes or unknown or bad:
    sys.exit(f"duplicate ids {dupes}; status rows without a feature {unknown}; unknown statuses {bad}")

counts = collections.Counter()
body = []
for fid, name, ref, ours, prio, deps in features:
    st, ev, lim = status.get(fid, ["Not implemented", "", ""])
    counts[st] += 1
    esc = lambda s: s.replace("|", "\\|")
    body.append(f"| {fid} | {esc(name)} | {esc(ref)} | {esc(ours)} | {prio} | {deps} | {LABEL[st]} | {esc(ev) or '-'} | {esc(lim) or '-'} |")

total = len(features)
out = [
    "# Feature parity matrix",
    "",
    "Generated by `python3 scripts/parity.py` from `docs/parity/features.tsv` and `docs/parity/status.tsv`.",
    "Edit those files, not this one. IDs starting with `X-` are capabilities found in the reference product that the",
    "master prompt does not list. \"Verified\" means automated tests (named in Evidence) exercise the real implementation;",
    "an integration that has only been run against a fake remote service is \"not fully verified\".",
    "",
    "## Summary",
    "",
    "| Status | Features |",
    "|---|---|",
]
for key in LABEL:
    if counts[key]:
        out.append(f"| {LABEL[key]} | {counts[key]} |")
out += [f"| **Total** | **{total}** |", "",
        "## Matrix", "",
        "| Feature ID | Feature | Reference capability | Our implementation | Priority | Dependencies | Status | Evidence | Limitations |",
        "|---|---|---|---|---|---|---|---|---|"] + body + [""]
(root / "docs/FEATURE_PARITY_MATRIX.md").write_text("\n".join(out), encoding="utf-8")
print(", ".join(f"{LABEL[k]}: {counts[k]}" for k in LABEL if counts[k]), f"| total {total}")
